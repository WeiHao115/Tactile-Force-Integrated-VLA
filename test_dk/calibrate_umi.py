import numpy as np

def compute_transformation_matrix(P1_points, P2_points):
    """
    通过多组点对计算 4x4 齐次变换矩阵 (右乘格式: P1 * T = P2)。
    
    参数:
    P1_points: numpy array, 维度为 [N, 3] 或 [N, 4], 源点云
    P2_points: numpy array, 维度为 [N, 3] 或 [N, 4], 目标点云
    
    返回:
    T: numpy array, 维度为 [4, 4], 最优齐次变换矩阵
    """
    # 提取前三维坐标 (X, Y, Z)
    A = np.array(P1_points)[:, :3]
    B = np.array(P2_points)[:, :3]
    
    # 1. 计算质心
    centroid_A = np.mean(A, axis=0)
    centroid_B = np.mean(B, axis=0)
    
    # 2. 去质心化
    A_centered = A - centroid_A
    B_centered = B - centroid_B
    
    # 3. 计算协方差矩阵 H
    H = np.dot(A_centered.T, B_centered)
    
    # 4. 奇异值分解 SVD
    U, S, Vt = np.linalg.svd(H)
    
    # 5. 计算旋转矩阵 R
    R = np.dot(U, Vt)
    
    # 反射校验：确保 R 是一个旋转矩阵
    if np.linalg.det(R) < 0:
        U[:, 2] *= -1
        R = np.dot(U, Vt)
        
    # 6. 计算平移向量 t
    t = centroid_B - np.dot(centroid_A, R)
    
    # 7. 组装 4x4 齐次变换矩阵
    T = np.eye(4)
    T[:3, :3] = R
    T[3, :3] = t  # 注意此处是将 t 放在最后一行，符合右乘 P1 * T = P2 的格式
    
    return T

